create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  tournament_name text not null check (char_length(tournament_name) between 1 and 120),
  team_a text not null check (char_length(team_a) between 1 and 100),
  team_b text not null check (char_length(team_b) between 1 and 100),
  match_date timestamptz not null,
  venue text,
  status text not null default 'upcoming' check (status in ('upcoming','live','completed')),
  score_a integer not null default 0 check (score_a >= 0),
  score_b integer not null default 0 check (score_b >= 0),
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.champions (
  id bigint generated by default as identity primary key,
  tournament_name text not null check (char_length(tournament_name) between 1 and 120),
  champion_name text not null check (char_length(champion_name) between 1 and 100),
  runner_up text,
  result_date date,
  description text check (description is null or char_length(description) <= 1000),
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists matches_public_date_idx on public.matches (match_date) where is_published = true;
create index if not exists champions_public_date_idx on public.champions (result_date desc) where is_published = true;

alter table public.profiles enable row level security;
alter table public.matches enable row level security;
alter table public.champions enable row level security;

-- Security-definer helper avoids recursive RLS checks on profiles.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.user_id = (select auth.uid()) and p.role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

drop policy if exists "profile_select_self" on public.profiles;
create policy "profile_select_self" on public.profiles
for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "public_read_published_matches" on public.matches;
create policy "public_read_published_matches" on public.matches
for select to anon, authenticated using (is_published = true);

drop policy if exists "admin_read_all_matches" on public.matches;
create policy "admin_read_all_matches" on public.matches
for select to authenticated using ((select public.is_admin()));

drop policy if exists "admin_insert_matches" on public.matches;
create policy "admin_insert_matches" on public.matches
for insert to authenticated with check ((select public.is_admin()));

drop policy if exists "admin_update_matches" on public.matches;
create policy "admin_update_matches" on public.matches
for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "admin_delete_matches" on public.matches;
create policy "admin_delete_matches" on public.matches
for delete to authenticated using ((select public.is_admin()));

drop policy if exists "public_read_published_champions" on public.champions;
create policy "public_read_published_champions" on public.champions
for select to anon, authenticated using (is_published = true);

drop policy if exists "admin_read_all_champions" on public.champions;
create policy "admin_read_all_champions" on public.champions
for select to authenticated using ((select public.is_admin()));

drop policy if exists "admin_insert_champions" on public.champions;
create policy "admin_insert_champions" on public.champions
for insert to authenticated with check ((select public.is_admin()));

drop policy if exists "admin_update_champions" on public.champions;
create policy "admin_update_champions" on public.champions
for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "admin_delete_champions" on public.champions;
create policy "admin_delete_champions" on public.champions
for delete to authenticated using ((select public.is_admin()));

